function IconBase({ name, size = 24, color, fill = false, style }: {
  name: IconName;
  size?: number;
  color?: string;
  fill?: boolean | 0 | 1;
  style?: StyleProp<ViewStyle>;
}) {
  const { c } = useTheme();
  const Glyph = ICONS[name] ?? CircleHelp;
  return (
    <Glyph
      size={size}
      color={color ?? c.text1}
      strokeWidth={2.2}
      fill={fill ? (color ?? c.text1) : 'none'}
      style={style}
    />
  );
}

export const Icon = memo(IconBase);